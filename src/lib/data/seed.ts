// The demo "today". All seed dates are relative to this so the calendar always looks alive.
export const DEMO_TODAY = "2026-09-14T09:00:00-04:00";

function d(daysFromToday: number, hour = 9, minute = 0): string {
  const base = new Date(DEMO_TODAY);
  base.setDate(base.getDate() + daysFromToday);
  base.setHours(hour, minute, 0, 0);
  return base.toISOString();
}
function day(daysFromToday: number): string {
  return d(daysFromToday).slice(0, 10);
}

